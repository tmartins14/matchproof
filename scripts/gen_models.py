"""Generate Pydantic v2 models from every schemas/*.schema.json.

All schemas are bundled into one document (cross-file $refs rewritten to local
$defs pointers) so datamodel-code-generator emits a single models.py.

Usage: gen_models.py [output_path]
"""

import json
import sys
from pathlib import Path
from typing import Any

from datamodel_code_generator import InputFileType, PythonVersion, generate
from datamodel_code_generator.enums import DataModelType

ROOT = Path(__file__).resolve().parent.parent
SCHEMAS_DIR = ROOT / "schemas"
DEFAULT_OUTPUT = ROOT / "packages" / "contracts" / "src" / "contracts" / "models.py"
HEADER = "# Generated by scripts/gen_models.py from schemas/*.schema.json. Do not edit."


def stem(path: str) -> str:
    return path.removesuffix(".schema.json")


def rewrite_refs(node: Any, current: str) -> Any:
    if isinstance(node, dict):
        out: dict[str, Any] = {}
        for key, value in node.items():
            if key == "$ref" and isinstance(value, str):
                file, _, fragment = value.partition("#")
                target = stem(file) if file else current
                out[key] = f"#/$defs/{target}{fragment}"
            elif key in ("$id", "$schema"):
                continue
            else:
                out[key] = rewrite_refs(value, current)
        return out
    if isinstance(node, list):
        return [rewrite_refs(item, current) for item in node]
    return node


def bundle() -> dict[str, Any]:
    defs: dict[str, Any] = {}
    for path in sorted(SCHEMAS_DIR.glob("*.schema.json")):
        name = stem(path.name)
        defs[name] = rewrite_refs(json.loads(path.read_text()), name)
    return {"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": defs}


def generate_models(output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    generate(
        json.dumps(bundle()),
        input_file_type=InputFileType.JsonSchema,
        output=output,
        output_model_type=DataModelType.PydanticV2BaseModel,
        target_python_version=PythonVersion.PY_312,
        custom_file_header=HEADER,
        disable_timestamp=True,
        use_annotated=True,
        field_constraints=True,
    )


def main() -> None:
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUTPUT
    generate_models(output)
    print(f"wrote {output}")


if __name__ == "__main__":
    main()
