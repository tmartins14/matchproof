// Generate TypeScript types from every schemas/*.schema.json.
// Usage: node scripts/gen_types.mjs [outputPath]
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemasDir = join(root, "schemas");
const defaultOutput = join(root, "apps", "web", "src", "contracts", "types.ts");
const require = createRequire(join(root, "apps", "web", "package.json"));
const { compile } = require("json-schema-to-typescript");

const header = "// Generated by scripts/gen_types.mjs from schemas/*.schema.json. Do not edit.";
const stem = (name) => name.replace(/\.schema\.json$/, "");

function rewriteRefs(node, current) {
  if (Array.isArray(node)) return node.map((item) => rewriteRefs(item, current));
  if (node === null || typeof node !== "object") return node;
  const out = {};
  const isTuple = Array.isArray(node.prefixItems);
  for (const [key, value] of Object.entries(node)) {
    // json-schema-to-typescript reads draft-07 tuples (items: [...]), not prefixItems.
    // Other min/maxItems would expand into huge fixed-length tuples, so drop them.
    if (key === "prefixItems") {
      out.items = rewriteRefs(value, current);
      out.additionalItems = false;
    } else if (key === "items" && isTuple) {
      continue;
    } else if ((key === "minItems" || key === "maxItems") && !isTuple) {
      continue;
    } else if (key === "$ref" && typeof value === "string") {
      const [file, fragment = ""] = value.split("#");
      out[key] = `#/$defs/${file ? stem(file) : current}${fragment}`;
    } else if (key !== "$id" && key !== "$schema") {
      out[key] = rewriteRefs(value, current);
    }
  }
  return out;
}

function bundle() {
  const defs = {};
  const files = readdirSync(schemasDir).filter((f) => f.endsWith(".schema.json")).sort();
  for (const file of files) {
    const name = stem(file);
    defs[name] = rewriteRefs(JSON.parse(readFileSync(join(schemasDir, file), "utf8")), name);
  }
  const properties = Object.fromEntries(Object.keys(defs).map((n) => [n, { $ref: `#/$defs/${n}` }]));
  return { title: "Contracts", type: "object", properties, additionalProperties: false, $defs: defs };
}

const output = process.argv[2] ? resolve(process.argv[2]) : defaultOutput;
const ts = await compile(bundle(), "Contracts", {
  bannerComment: header,
  additionalProperties: false,
  format: false,
});
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, ts);
console.log(`wrote ${output}`);
